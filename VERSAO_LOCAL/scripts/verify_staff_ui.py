"""Conferência curta de cadastro, busca e transferência na página de usuários."""
from pathlib import Path
import sys
from playwright.sync_api import sync_playwright,expect
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'RADACHE_Modulo_Alunos/backend/tests'))
import test_staff

fixture=test_staff.StaffFlow('test_multicourse_and_transfer');fixture.setUp()
out=ROOT/'validacao/funcionarios';out.mkdir(parents=True,exist_ok=True)
try:
    with sync_playwright() as p:
        browser=p.chromium.launch(executable_path=r'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe',headless=True)
        context=browser.new_context(viewport={'width':1440,'height':1000})
        context.route('**/*',lambda r:r.continue_() if r.request.url.startswith(fixture.base+'/') else r.abort())
        page=context.new_page();errors=[];page.on('pageerror',lambda error:errors.append(str(error)))
        page.goto(fixture.base+'/gestao/#usuarios')
        page.locator('#login-email').fill('admin@radache.local');page.locator('#login-password').fill('admin123');page.locator('#login-submit').click()
        expect(page.locator('#users-page')).to_be_visible()
        page.locator('#create-user-button').click()
        page.locator('#user-form input[name="nome"]').fill('TESTE Ana multicurso')
        page.locator('#user-form input[name="email"]').fill('ana-multi-ui')
        page.locator('#user-initial-password').fill('Inicial#2026')
        expect(page.locator('#user-course option[value="direito"]')).to_have_count(1)
        page.locator('#user-course').select_option(['ciencia-da-computacao','direito']);page.locator('#user-save').click()
        expect(page.locator('#user-dialog')).not_to_be_visible()
        expect(page.locator('#users-body')).to_contain_text('TESTE Ana multicurso')
        row=page.locator('#users-body tr').filter(has_text='ana-multi-ui')
        expect(row).to_contain_text('Direito');expect(row).to_contain_text('Ciência da Computação')
        page.locator('#staff-search').fill('ana-multi-ui');page.locator('#staff-find').click()
        expect(page.locator('#staff-results')).to_contain_text('TESTE Ana multicurso')
        page.locator('#staff-results button').click()
        expect(page.locator('#user-campus')).to_be_disabled()
        expect(page.locator('#user-save')).to_be_enabled()
        expect(page.locator('#user-course option:checked')).to_have_count(2)
        page.locator('#user-dialog [data-close-dialog]').first.click()
        expect(page.locator('#user-dialog')).not_to_be_visible()
        row.get_by_role('button',name='Histórico',exact=True).click()
        expect(page.locator('#staff-history')).to_contain_text('Direito')
        page.locator('#staff-history').get_by_role('button',name='Fechar',exact=True).click()
        row.get_by_role('button',name='Transferir de câmpus').click()
        page.locator('#staff-destination').select_option('cuiaba')
        expect(page.locator('#staff-destination-courses option[value="ciencia-da-computacao"]')).to_have_count(1)
        page.locator('#staff-destination-courses').select_option('ciencia-da-computacao')
        page.locator('#staff-transfer-reason').fill('Transferência administrativa de teste')
        page.locator('#staff-transfer').get_by_role('button',name='Confirmar transferência').click()
        expect(page.locator('#staff-transfer')).not_to_be_visible()
        expect(page.locator('#staff-transfers')).to_contain_text('concluida')
        expect(row).to_contain_text('Cuiabá')
        page.locator('#refresh-button').click();expect(page.locator('#refresh-button')).to_be_enabled()
        page.screenshot(path=str(out/'usuarios.png'),full_page=True)
        page.locator('#logout-button').click()
        page.locator('#login-email').fill('ana-multi-ui');page.locator('#login-password').fill('Inicial#2026');page.locator('#login-submit').click()
        expect(page.locator('#page-title')).to_have_text('Meus Atendimentos')
        expect(page.locator('#scope-description')).to_contain_text('Cuiabá')
        assert not errors,errors
        browser.close()
    print('OK: cadastro com login/senha e dois cursos; busca reutiliza conta; lotação bloqueada; histórico; transferência e login no destino.')
finally:fixture.tearDown()
